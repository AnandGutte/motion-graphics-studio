#!/usr/bin/env python3
"""
Cross-Platform Neural TTS Generator for Motion Graphics Studio.
- On macOS Apple Silicon: Uses kokoro-mlx (Metal acceleration).
- On Windows 11 (NVIDIA RTX 4070) & Linux: Uses kokoro (PyTorch CUDA / CPU) or kokoro-onnx.
All model weights, caches, and output files stay inside the workspace.
"""

import os
import sys
import argparse
import platform
from pathlib import Path

# Enforce project-local caches and environment
PROJECT_ROOT = Path(__file__).resolve().parent.parent
os.environ["HF_HOME"] = str(PROJECT_ROOT / ".cache" / "huggingface")
os.environ["XDG_CACHE_HOME"] = str(PROJECT_ROOT / ".cache")
os.environ["TMPDIR"] = str(PROJECT_ROOT / ".tmp")

# On macOS, ensure ESPEAK_DATA_PATH points to tools
if (PROJECT_ROOT / "tools" / "espeak-ng-data").exists():
    os.environ["ESPEAK_DATA_PATH"] = str(PROJECT_ROOT / "tools")

def synthesize_macos_mlx(text: str, voice: str, output_path: str, speed: float, sample_rate: int):
    """Synthesize speech using kokoro-mlx on Apple Silicon."""
    from kokoro_mlx import KokoroTTS
    print(f"[macOS MLX] Loading Kokoro TTS model (cache: {os.environ['HF_HOME']})...")
    tts = KokoroTTS.from_pretrained("mlx-community/Kokoro-82M-bf16")
    print(f"[macOS MLX] Generating speech: voice='{voice}', speed={speed}, sample_rate={sample_rate}...")
    tts.save(text=text, path=output_path, voice=voice, speed=speed, sample_rate=sample_rate)

def synthesize_windows_pytorch(text: str, voice: str, output_path: str, speed: float, sample_rate: int):
    """Synthesize speech using kokoro (PyTorch CUDA/CPU) on Windows."""
    try:
        from kokoro import KPipeline
        import soundfile as sf
        import torch

        device = "cuda" if torch.cuda.is_available() else "cpu"
        print(f"[Windows PyTorch] Initializing Kokoro pipeline on device={device}...")
        pipeline = KPipeline(lang_code="a", device=device)

        print(f"[Windows PyTorch] Generating speech: voice='{voice}', speed={speed}...")
        generator = pipeline(text, voice=voice, speed=speed)

        audio_segments = []
        for _, _, audio in generator:
            audio_segments.append(audio)

        if audio_segments:
            import numpy as np
            full_audio = np.concatenate(audio_segments)
            sf.write(output_path, full_audio, sample_rate)
        else:
            raise RuntimeError("No audio was generated by the pipeline.")

    except ImportError:
        # Fallback to kokoro-onnx if installed
        try:
            from kokoro_onnx import Kokoro
            import soundfile as sf
            print("[Windows ONNX] Falling back to kokoro-onnx...")
            model_path = os.environ.get("KOKORO_MODEL_PATH", str(PROJECT_ROOT / ".cache" / "kokoro-v0_19.onnx"))
            voices_path = os.environ.get("KOKORO_VOICES_PATH", str(PROJECT_ROOT / ".cache" / "voices.json"))
            kokoro = Kokoro(model_path, voices_path)
            samples, sr = kokoro.create(text, voice=voice, speed=speed, lang="en-us")
            sf.write(output_path, samples, sr)
        except ImportError:
            print("Error: Neither 'kokoro-mlx' nor 'kokoro' (PyTorch) is installed.", file=sys.stderr)
            print("On Windows 11 with NVIDIA GPU, install via: pip install kokoro soundfile torch --index-url https://download.pytorch.org/whl/cu121", file=sys.stderr)
            sys.exit(1)

def main():
    parser = argparse.ArgumentParser(description="Cross-Platform Kokoro Neural Voice Generator.")
    parser.add_argument("--text", "-t", required=True, help="Text to synthesize")
    parser.add_argument("--voice", "-v", default="am_adam", help="Voice identifier (e.g. am_adam, am_michael, af_heart)")
    parser.add_argument("--output", "-o", required=True, help="Output WAV path")
    parser.add_argument("--speed", "-s", type=float, default=1.05, help="Speech rate multiplier (default: 1.05)")
    parser.add_argument("--sample-rate", "-r", type=int, default=24000, help="Output sample rate (default: 24000)")
    args = parser.parse_args()

    out_path = Path(args.output).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    is_apple_silicon = platform.system() == "Darwin" and platform.machine() == "arm64"

    if is_apple_silicon:
        try:
            synthesize_macos_mlx(args.text, args.voice, str(out_path), args.speed, args.sample_rate)
        except ImportError:
            synthesize_windows_pytorch(args.text, args.voice, str(out_path), args.speed, args.sample_rate)
    else:
        synthesize_windows_pytorch(args.text, args.voice, str(out_path), args.speed, args.sample_rate)

    if out_path.exists() and out_path.stat().st_size > 0:
        print(f"Generated audio successfully: {out_path} ({out_path.stat().st_size} bytes)")
    else:
        print("Error: Output file was not generated or is empty.", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
